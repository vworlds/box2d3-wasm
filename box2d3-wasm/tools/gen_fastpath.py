#!/usr/bin/env python3
"""Generate the b2x_Body_* fast-path wrappers from Box2D's public header.

    python3 tools/gen_fastpath.py            # writes csrc/fastpath_body.gen.cpp, src/fastpath_body.gen.d.ts
    python3 tools/gen_fastpath.py --check    # exit 1 if the committed files are stale

Every b2Body_* function in include/box2d/box2d.h becomes b2x_Body_<Name> with plain i32/f32
arguments: the body id as (index1, rev), b2Vec2/b2Rot/b2Transform/b2MassData arguments flattened
to floats, bools and enums as ints. Struct results (b2Vec2, b2Rot, b2Transform, b2AABB,
b2MassData) are written to a caller-supplied float* `out`; id arrays to an int32* as
(index1, rev) pairs. Each wrapper calls exactly the function it is named after, so it computes
exactly what the embind binding computes.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT.parent / "box2d" / "include" / "box2d" / "box2d.h"
OUT_CPP = ROOT / "csrc" / "fastpath_body.gen.cpp"
OUT_DTS = ROOT / "src" / "fastpath_body.gen.d.ts"

# Hand-written in fastpath.cpp (integer user data), or not expressible as numbers.
SKIP = {"SetUserData", "GetUserData", "SetName", "GetName", "GetContactData"}

# type -> (list of (suffix, c type, ts doc)), and how to rebuild the C value from the args
PARAM_TYPES = {
    "float": ([("", "float")], "{n}"),
    "int": ([("", "int32_t")], "{n}"),
    "bool": ([("", "int32_t")], "({n} != 0)"),
    "b2BodyType": ([("", "int32_t")], "(b2BodyType){n}"),
    "b2Vec2": ([("X", "float"), ("Y", "float")], "b2Vec2{{ {n}X, {n}Y }}"),
    "b2Rot": ([("C", "float"), ("S", "float")], "b2Rot{{ {n}C, {n}S }}"),
    "b2Transform": (
        [("Px", "float"), ("Py", "float"), ("Qc", "float"), ("Qs", "float")],
        "b2Transform{{ b2Vec2{{ {n}Px, {n}Py }}, b2Rot{{ {n}Qc, {n}Qs }} }}",
    ),
    "b2MassData": (
        [("Mass", "float"), ("CenterX", "float"), ("CenterY", "float"), ("RotationalInertia", "float")],
        "b2MassData{{ {n}Mass, b2Vec2{{ {n}CenterX, {n}CenterY }}, {n}RotationalInertia }}",
    ),
    "b2MotionLocks": (
        [("", "int32_t")],
        "b2MotionLocks{{ ({n} & 1) != 0, ({n} & 2) != 0, ({n} & 4) != 0 }}",
    ),
}

# return type -> (c return type, body template, out floats or None, doc)
RETURN_TYPES = {
    "void": ("void", "{call};", None, ""),
    "float": ("float", "return {call};", None, ""),
    "int": ("int32_t", "return {call};", None, ""),
    "bool": ("int32_t", "return {call} ? 1 : 0;", None, "1 or 0"),
    "b2BodyType": ("int32_t", "return (int32_t){call};", None, "b2BodyType value"),
    "b2WorldId": (
        "int32_t",
        "b2WorldId w = {call};\n\treturn (int32_t)( (uint32_t)w.index1 | ( (uint32_t)w.generation << 16 ) );",
        None,
        "packed world id",
    ),
    "b2MotionLocks": (
        "int32_t",
        "b2MotionLocks l = {call};\n\treturn ( l.linearX ? 1 : 0 ) | ( l.linearY ? 2 : 0 ) | ( l.angularZ ? 4 : 0 );",
        None,
        "bits: 1 linearX, 2 linearY, 4 angularZ",
    ),
    "b2Vec2": ("void", "b2Vec2 v = {call};\n\tout[0] = v.x;\n\tout[1] = v.y;", 2, "out: x, y"),
    "b2Rot": ("void", "b2Rot q = {call};\n\tout[0] = q.c;\n\tout[1] = q.s;", 2, "out: c, s"),
    "b2Transform": (
        "void",
        "b2Transform t = {call};\n\tout[0] = t.p.x;\n\tout[1] = t.p.y;\n\tout[2] = t.q.c;\n\tout[3] = t.q.s;",
        4,
        "out: px, py, qc, qs",
    ),
    "b2AABB": (
        "void",
        "b2AABB a = {call};\n\tout[0] = a.lowerBound.x;\n\tout[1] = a.lowerBound.y;\n\tout[2] = a.upperBound.x;\n\tout[3] = a.upperBound.y;",
        4,
        "out: lowerX, lowerY, upperX, upperY",
    ),
    "b2MassData": (
        "void",
        "b2MassData m = {call};\n\tout[0] = m.mass;\n\tout[1] = m.center.x;\n\tout[2] = m.center.y;\n\tout[3] = m.rotationalInertia;",
        4,
        "out: mass, centerX, centerY, rotationalInertia",
    ),
}

ID_ARRAYS = {"b2ShapeId*": "b2ShapeId", "b2JointId*": "b2JointId"}


def parse():
    text = HEADER.read_text()
    pattern = re.compile(r"B2_API\s+(const\s+char\*|void\*|[\w]+)\s+b2Body_(\w+)\(\s*([^)]*)\);")
    for match in pattern.finditer(text):
        ret, name, params = match.group(1).strip(), match.group(2), match.group(3)
        args = [p.strip() for p in params.split(",")]
        yield ret, name, args


def generate():
    cpp = [
        "// GENERATED by tools/gen_fastpath.py from box2d/include/box2d/box2d.h. Do not edit.",
        "// b2x_Body_<Name>(index1, rev, ...) calls b2Body_<Name> with the same values.",
        '#include <box2d/box2d.h>',
        '#include <emscripten.h>',
        '#include <cstddef>',
        '#include <cstdint>',
        "",
        "#define B2X_API extern \"C\" EMSCRIPTEN_KEEPALIVE",
        "",
        "static_assert( sizeof( b2ShapeId ) == 8 && offsetof( b2ShapeId, world0 ) == 4 && offsetof( b2ShapeId, generation ) == 6, \"b2ShapeId must be the (index1, rev) word pair\" );",
        "static_assert( sizeof( b2JointId ) == 8 && offsetof( b2JointId, world0 ) == 4 && offsetof( b2JointId, generation ) == 6, \"b2JointId must be the (index1, rev) word pair\" );",
        "",
        "static inline b2BodyId B2xBody( int32_t index1, int32_t rev )",
        "{",
        "\treturn b2BodyId{ index1, (uint16_t)( (uint32_t)rev & 0xffffu ), (uint16_t)( (uint32_t)rev >> 16 ) };",
        "}",
        "",
    ]
    dts = [
        "// GENERATED by tools/gen_fastpath.py from box2d/include/box2d/box2d.h. Do not edit.",
        "/** Raw b2x_Body_* exports on the module: body id as (index1, rev). Struct results go to `out`. */",
        "export interface FastPathBodyExports {",
    ]
    names = []
    skipped = []
    for ret, name, args in parse():
        if name in SKIP:
            skipped.append(name)
            continue
        assert args[0].startswith("b2BodyId"), (name, args)
        c_params = ["int32_t index1", "int32_t rev"]
        ts_params = ["index1: number", "rev: number"]
        call_args = ["B2xBody( index1, rev )"]
        ok = True
        rest = args[1:]
        i = 0
        while i < len(rest):
            arg = rest[i]
            ctype, pname = arg.rsplit(" ", 1)
            ctype = ctype.strip()
            if ctype in ID_ARRAYS:
                # (array, capacity) -> int32 pairs + capacity
                cap = rest[i + 1].rsplit(" ", 1)[1]
                c_params += [f"int32_t* {pname}", f"int32_t {cap}"]
                ts_params += [f"{pname}Ptr: number", f"{cap}: number"]
                call_args.append(None)  # filled below
                id_array = (ID_ARRAYS[ctype], pname, cap)
                i += 2
                continue
            if ctype not in PARAM_TYPES:
                ok = False
                break
            parts, rebuild = PARAM_TYPES[ctype]
            for suffix, t in parts:
                c_params.append(f"{t} {pname}{suffix}")
                ts_params.append(f"{pname}{suffix}: number")
            call_args.append(rebuild.format(n=pname))
            i += 1
        if not ok or ret not in RETURN_TYPES:
            skipped.append(name)
            continue
        c_ret, body, out_floats, doc = RETURN_TYPES[ret]
        if out_floats:
            c_params.append("float* out")
            ts_params.append("outPtr: number")
        if None in call_args:
            elem, pname, cap = id_array
            idx = call_args.index(None)
            call = (
                f"\t// {elem} is (int32 index1, uint16 world0, uint16 generation): in memory exactly the\n"
                f"\t// (index1, rev) word pair, so Box2D writes straight into the caller's buffer.\n"
                f"\treturn b2Body_{name}( {call_args[0]}, ({elem}*){pname}, {cap} );"
            )
            del call_args[idx]
            body_text = call
            doc = f"writes up to capacity (index1, rev) pairs to {pname}Ptr; returns the count"
        else:
            body_text = "\t" + body.format(call=f"b2Body_{name}( {', '.join(call_args)} )")
        cpp += [f"B2X_API {c_ret} b2x_Body_{name}( {', '.join(c_params)} )", "{", body_text, "}", ""]
        ts_ret = "void" if c_ret == "void" else "number"
        if doc:
            dts.append(f"  /** {doc} */")
        dts.append(f"  _b2x_Body_{name}({', '.join(ts_params)}): {ts_ret};")
        names.append(name)
    dts.append("}")
    dts.append("")
    dts.append(f"/** Box2D b2Body_* functions without a generated wrapper: {', '.join(sorted(skipped))}. */")
    dts.append("export type FastPathBodySkipped = " + " | ".join(f'"{s}"' for s in sorted(skipped)) + ";")
    return "\n".join(cpp) + "\n", "\n".join(dts) + "\n", names, skipped


def main():
    cpp, dts, names, skipped = generate()
    if "--check" in sys.argv:
        stale = OUT_CPP.read_text() != cpp or OUT_DTS.read_text() != dts
        print("stale" if stale else "up to date")
        sys.exit(1 if stale else 0)
    OUT_CPP.write_text(cpp)
    OUT_DTS.write_text(dts)
    print(f"generated {len(names)} wrappers; skipped {len(skipped)}: {', '.join(skipped)}")


if __name__ == "__main__":
    main()
